import { useState } from 'react';
import { useQuery, useQueryClient } from '@tanstack/react-query';
import { Sparkles, Tags, X } from 'lucide-react';
import { communityApi as api } from './communityApi';
import type { Post } from './communityApi';

export function TagBadges({ tags = [], category }: { tags?: string[]; category?: string }) {
  return (
    <div className="tag-badges">
      {category && <span className="category-badge">{category}</span>}
      {tags.map((tag) => (
        <span className="tag-badge" key={tag}>
          #{tag}
        </span>
      ))}
    </div>
  );
}

export default function PostTags({
  serverId,
  post,
  manager,
}: {
  serverId: string;
  post: Post;
  manager: boolean;
}) {
  const client = useQueryClient();
  const [draft, setDraft] = useState((post.tags || []).join(', '));
  const [suggestions, setSuggestions] = useState<string[] | null>(null);
  const [busy, setBusy] = useState('');
  const [error, setError] = useState('');
  const [saved, setSaved] = useState(false);
  const config = useQuery({
    queryKey: ['community', serverId, 'ai'],
    queryFn: () => api<{ enabled: boolean; model: string }>(`/servers/${serverId}/ai`),
    enabled: manager,
  });
  const base = `/servers/${serverId}/posts/${post.id}/tags`;
  const hasImages = post.media.some((m) => m.kind === 'image');
  return (
    <section className="post-tags" aria-label="Post tags">
      <div className="post-gallery-heading">
        <h2>
          <Tags size={18} /> Tags
        </h2>
        <span>{post.tags?.length || 0} tags</span>
      </div>
      <TagBadges tags={post.tags} category={post.category} />
      {post.tags_source === 'ai' && (
        <p className="hint">
          <Sparkles size={13} /> Automatically generated by AI. A server administrator can review
          and edit these tags.
        </p>
      )}
      {!post.tags?.length && <p className="hint">No tags yet.</p>}
      {manager && (
        <details>
          <summary>Edit tags and AI suggestions</summary>
          <p className="hint">
            Tags belong to this server. AI suggestions are saved only after you review and apply
            them.
          </p>
          <fieldset disabled={!!busy}>
            <label>
              Post tags
              <textarea
                aria-label="Post tags"
                rows={3}
                maxLength={1500}
                value={draft}
                onChange={(e) => {
                  setDraft(e.target.value);
                  setSaved(false);
                }}
                placeholder="digital_art, landscape, blue_sky"
              />
              <small>Up to 30 tags, separated by commas. Spaces become underscores.</small>
            </label>
            <div className="tag-editor-actions">
              <button
                className="button primary"
                onClick={async () => {
                  setBusy('save');
                  setError('');
                  setSaved(false);
                  try {
                    const value = await api<{ tags: string[] }>(base, 'PUT', {
                      tags: draft
                        .split(',')
                        .map((t) => t.trim())
                        .filter(Boolean),
                    });
                    setDraft(value.tags.join(', '));
                    await client.invalidateQueries({ queryKey: ['community', serverId] });
                    setSaved(true);
                  } catch (e) {
                    setError((e as Error).message);
                  } finally {
                    setBusy('');
                  }
                }}
              >
                {busy === 'save' ? 'Saving…' : 'Save tags'}
              </button>
              <button
                className="button secondary"
                disabled={!config.data?.enabled || !hasImages}
                onClick={async () => {
                  setBusy('suggest');
                  setError('');
                  setSaved(false);
                  setSuggestions(null);
                  try {
                    const value = await api<{ tags: string[] }>(`${base}/suggest`, 'POST', {});
                    setSuggestions(value.tags);
                  } catch (e) {
                    setError((e as Error).message);
                  } finally {
                    setBusy('');
                  }
                }}
              >
                <Sparkles size={16} />
                {busy === 'suggest' ? 'Analyzing…' : 'Suggest with AI'}
              </button>
            </div>
            <p className="hint">
              {config.isError
                ? config.error.message
                : config.isPending
                  ? 'Checking AI availability…'
                  : !config.data?.enabled
                    ? 'Image tagging is not configured. Ask the installation administrator to set WD_TAGGER_URL. Manual tags are available.'
                    : !hasImages
                      ? 'This post has no images to analyze. You can still add tags manually.'
                      : 'WD analyzes up to two images on the configured local service. Results work best for illustrations; review tags for photography and 3D artwork.'}
            </p>
            {suggestions !== null && (
              <div className="tag-suggestions">
                <strong>
                  <Sparkles size={15} /> Review suggestions
                </strong>
                {suggestions.length ? (
                  <>
                    <div className="tag-badges">
                      {suggestions.map((tag) => (
                        <button
                          className="tag-badge"
                          key={tag}
                          aria-label={`Remove suggestion ${tag}`}
                          onClick={() => setSuggestions(suggestions.filter((t) => t !== tag))}
                        >
                          #{tag}
                          <X size={12} />
                        </button>
                      ))}
                    </div>
                    <button
                      className="button secondary"
                      onClick={() => {
                        setDraft(
                          [
                            ...new Set([
                              ...draft
                                .split(',')
                                .map((t) => t.trim())
                                .filter(Boolean),
                              ...suggestions,
                            ]),
                          ].join(', '),
                        );
                        setSuggestions(null);
                        setSaved(false);
                      }}
                    >
                      Add to draft
                    </button>
                  </>
                ) : (
                  <p>The model found no supported tags. You can add tags manually.</p>
                )}
              </div>
            )}
          </fieldset>
          {saved && <p role="status">Tags saved.</p>}
          {error && (
            <p role="alert" className="error">
              {error}
            </p>
          )}
        </details>
      )}
    </section>
  );
}
